#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<'EOF'
One-shot setup for SuperTokens Core on Linux (no Docker + systemd).

Usage:
  sudo bash deploy/linux/setup-supertokens-core-systemd.sh --db-uri <uri> [options]

Required:
  --db-uri <uri>              SuperTokens metadata DB URI.
                              Example:
                                postgresql://supertokens:pass@127.0.0.1:5432/supertokens
                                mysql://supertokens:pass@127.0.0.1:3306/supertokens

Options:
  --plugin <postgresql|mysql> Image flavor. Default: postgresql
  --tag <version>             Image tag. Defaults:
                              postgresql -> 11.4.4
                              mysql      -> 10.1.4
  --port <number>             Core port. Default: 3567
  --api-key <value>           Optional API_KEYS value for Core
  --install-dir <path>        Install dir. Default: /opt/supertokens
  --env-path <path>           Env file path. Default: /etc/supertokens/core.env
  --service-path <path>       systemd file path. Default: /etc/systemd/system/supertokens-core.service
  --user <name>               Runtime user. Default: supertokens
  --group <name>              Runtime group. Default: supertokens
  --skip-enable               Do not run systemctl enable --now
  -h, --help                  Show help

Example:
  sudo bash deploy/linux/setup-supertokens-core-systemd.sh \
    --plugin postgresql \
    --db-uri "postgresql://supertokens:replace_me@127.0.0.1:5432/supertokens"
EOF
}

if [[ "$(id -u)" -ne 0 ]]; then
  echo "[error] please run as root (use sudo)." >&2
  exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
INSTALLER="${SCRIPT_DIR}/install-supertokens-core-no-docker.sh"

PLUGIN="postgresql"
TAG=""
PORT="3567"
DB_URI=""
API_KEY=""
INSTALL_DIR="/opt/supertokens"
ENV_PATH="/etc/supertokens/core.env"
SERVICE_PATH="/etc/systemd/system/supertokens-core.service"
RUNTIME_USER="supertokens"
RUNTIME_GROUP="supertokens"
SKIP_ENABLE="0"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --plugin)
      PLUGIN="${2:-}"
      shift 2
      ;;
    --tag)
      TAG="${2:-}"
      shift 2
      ;;
    --port)
      PORT="${2:-}"
      shift 2
      ;;
    --db-uri)
      DB_URI="${2:-}"
      shift 2
      ;;
    --api-key)
      API_KEY="${2:-}"
      shift 2
      ;;
    --install-dir)
      INSTALL_DIR="${2:-}"
      shift 2
      ;;
    --env-path)
      ENV_PATH="${2:-}"
      shift 2
      ;;
    --service-path)
      SERVICE_PATH="${2:-}"
      shift 2
      ;;
    --user)
      RUNTIME_USER="${2:-}"
      shift 2
      ;;
    --group)
      RUNTIME_GROUP="${2:-}"
      shift 2
      ;;
    --skip-enable)
      SKIP_ENABLE="1"
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "[error] unknown option: $1" >&2
      usage
      exit 1
      ;;
  esac
done

if [[ -z "${DB_URI}" ]]; then
  echo "[error] --db-uri is required" >&2
  exit 1
fi

if [[ ! "${PORT}" =~ ^[0-9]+$ ]] || [[ "${PORT}" -lt 1 ]] || [[ "${PORT}" -gt 65535 ]]; then
  echo "[error] --port must be a valid TCP port (1-65535)" >&2
  exit 1
fi

case "${PLUGIN}" in
  postgresql|postgres)
    PLUGIN="postgresql"
    [[ -n "${TAG}" ]] || TAG="11.4.4"
    if [[ "${DB_URI}" != postgresql://* ]]; then
      echo "[warn] plugin=postgresql but db-uri does not start with postgresql://"
    fi
    ;;
  mysql)
    [[ -n "${TAG}" ]] || TAG="10.1.4"
    if [[ "${DB_URI}" != mysql://* ]]; then
      echo "[warn] plugin=mysql but db-uri does not start with mysql://"
    fi
    ;;
  *)
    echo "[error] --plugin must be postgresql or mysql" >&2
    exit 1
    ;;
esac

if [[ ! -x "${INSTALLER}" ]]; then
  chmod +x "${INSTALLER}"
fi

echo "[step] install core files..."
bash "${INSTALLER}" \
  --plugin "${PLUGIN}" \
  --tag "${TAG}" \
  --install-dir "${INSTALL_DIR}" \
  --user "${RUNTIME_USER}" \
  --group "${RUNTIME_GROUP}"

ENV_DIR="$(dirname "${ENV_PATH}")"
install -d -m 0750 -o "${RUNTIME_USER}" -g "${RUNTIME_GROUP}" "${ENV_DIR}"

echo "[step] write ${ENV_PATH} ..."
{
  echo "# generated by setup-supertokens-core-systemd.sh"
  echo "PORT=${PORT}"
  if [[ "${PLUGIN}" == "mysql" ]]; then
    echo "MYSQL_CONNECTION_URI=${DB_URI}"
  else
    echo "POSTGRESQL_CONNECTION_URI=${DB_URI}"
  fi
  if [[ -n "${API_KEY}" ]]; then
    echo "API_KEYS=${API_KEY}"
  fi
} > "${ENV_PATH}"

chmod 0600 "${ENV_PATH}"
chown "${RUNTIME_USER}:${RUNTIME_GROUP}" "${ENV_PATH}"

echo "[step] write ${SERVICE_PATH} ..."
cat > "${SERVICE_PATH}" <<EOF
[Unit]
Description=SuperTokens Core
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=${RUNTIME_USER}
Group=${RUNTIME_GROUP}
EnvironmentFile=${ENV_PATH}
WorkingDirectory=${INSTALL_DIR}
ExecStart=${INSTALL_DIR}/supertokens
Restart=on-failure
RestartSec=5
LimitNOFILE=65535

[Install]
WantedBy=multi-user.target
EOF

chmod 0644 "${SERVICE_PATH}"

echo "[step] systemd reload..."
systemctl daemon-reload

if [[ "${SKIP_ENABLE}" != "1" ]]; then
  echo "[step] enable + start service..."
  systemctl enable --now supertokens-core
fi

echo "[check] curl http://127.0.0.1:${PORT}/hello"
if curl -fsS "http://127.0.0.1:${PORT}/hello" | grep -qi "hello"; then
  echo "[ok] SuperTokens Core is reachable."
else
  echo "[warn] /hello check failed. inspect logs:"
  echo "       journalctl -u supertokens-core -n 200 --no-pager"
fi

echo "[done] Next:"
echo "  1) backend env: set SUPERTOKENS_CONNECTION_URI=http://127.0.0.1:${PORT}"
if [[ -n "${API_KEY}" ]]; then
  echo "  2) backend env: set SUPERTOKENS_API_KEY=<same API key>"
fi
